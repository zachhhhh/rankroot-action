// Writes RankRoot fixes that the customer approved into this repository, in the form the site's framework serves.
// No dependencies. Inputs come from env (set by publish/action.yml). Outputs for the next steps:
//   $RUNNER_TEMP/rankroot-pr-body.md   pull request description
//   GITHUB_OUTPUT: count=<files written>, ids=<comma-separated fix ids>
import fs from "node:fs";
import path from "node:path";

const API = (process.env.RR_API || "https://getrankroot.com").replace(/\/$/, "");
const KEY = process.env.RR_KEY || "";
const ROOT = path.resolve(process.env.RR_WORKDIR || ".");
const forcedPublic = process.env.RR_PUBLIC_DIR || "";
const out = (k, v) => process.env.GITHUB_OUTPUT && fs.appendFileSync(process.env.GITHUB_OUTPUT, `${k}=${v}\n`);

if (!KEY) {
  console.log("::error::api-key is required (your RankRoot license key, stored as a repository secret).");
  process.exit(1);
}

const r = await fetch(`${API}/api/engine?format=publish`, { headers: { authorization: `Bearer ${KEY}` } });
if (!r.ok) {
  console.log(`::error::RankRoot API answered ${r.status}: ${(await r.text()).slice(0, 300)}`);
  process.exit(1);
}
const { items = [], domain = "" } = await r.json();
console.log(`RankRoot: ${items.length} approved fix(es) for ${domain || "your site"}`);

const exists = (p) => fs.existsSync(path.join(ROOT, p));
const pkg = (() => {
  try {
    return JSON.parse(fs.readFileSync(path.join(ROOT, "package.json"), "utf8"));
  } catch {
    return {};
  }
})();
const deps = { ...(pkg.dependencies || {}), ...(pkg.devDependencies || {}) };
const ts = exists("tsconfig.json");
const appDir = deps.next ? ["app", "src/app"].find(exists) : undefined;
const pagesDir = deps.next && !appDir ? ["pages", "src/pages"].find(exists) : undefined;
const publicDir = forcedPublic || (exists("public") ? "public" : exists("static") ? "static" : "public");
const framework = appDir ? `Next.js App Router (${appDir}/)` : pagesDir ? `Next.js Pages Router (${pagesDir}/)` : `static files in ${publicDir}/`;
console.log(`Detected: ${framework}`);

// Route segment from a site path like "/compare/acme-vs-rival" (lowercase, hyphens only).
const seg = (p) =>
  p
    .split("/")
    .filter(Boolean)
    .map((s) => s.toLowerCase().replace(/[^a-z0-9-]/g, "-"))
    .filter(Boolean)
    .join("/");

const ext = ts ? "tsx" : "jsx";
function nextAppPage(page) {
  const html = page.bodyHtml + "\n" + page.jsonLd.map((j) => `<script type="application/ld+json">${j.replace(/</g, "\\u003c")}</script>`).join("\n");
  return `// Generated by RankRoot from a fix you approved. Edit freely; RankRoot won't overwrite your changes.
${ts ? 'import type { Metadata } from "next";\n\n' : ""}export const metadata${ts ? ": Metadata" : ""} = ${JSON.stringify({ title: page.title, description: page.description || undefined, alternates: { canonical: page.canonical } }, null, 2)};

const html = ${JSON.stringify(html)};

export default function Page() {
  return <main style={{ maxWidth: 760, margin: "0 auto", padding: "32px 20px 64px" }} dangerouslySetInnerHTML={{ __html: html }} />;
}
`;
}
function nextPagesPage(page) {
  const html = page.bodyHtml;
  return `// Generated by RankRoot from a fix you approved. Edit freely; RankRoot won't overwrite your changes.
import Head from "next/head";

const html = ${JSON.stringify(html)};
const jsonLd = ${JSON.stringify(page.jsonLd)};

export default function Page() {
  return (
    <>
      <Head>
        <title>{${JSON.stringify(page.title)}}</title>
        ${page.description ? `<meta name="description" content={${JSON.stringify(page.description)}} />` : ""}
        <link rel="canonical" href={${JSON.stringify(page.canonical)}} />
        {jsonLd.map((j, i) => <script key={i} type="application/ld+json" dangerouslySetInnerHTML={{ __html: j.replace(/</g, "\\\\u003c") }} />)}
      </Head>
      <main style={{ maxWidth: 760, margin: "0 auto", padding: "32px 20px 64px" }} dangerouslySetInnerHTML={{ __html: html }} />
    </>
  );
}
`;
}

const written = [];
const skipped = [];
const manual = [];
const ids = [];
const write = (rel, content) => {
  const abs = path.join(ROOT, rel);
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
};

for (const it of items) {
  if (it.page) {
    const s = seg(it.path);
    if (!s) {
      skipped.push(`${it.title}: no usable path`);
      continue;
    }
    let rel;
    let taken;
    if (appDir) {
      rel = `${appDir}/${s}/page.${ext}`;
      taken = ["tsx", "jsx", "ts", "js", "mdx"].some((e) => exists(`${appDir}/${s}/page.${e}`)) || exists(`${appDir}/${s}/route.ts`);
    } else if (pagesDir) {
      rel = `${pagesDir}/${s}.${ext}`;
      taken = ["tsx", "jsx", "ts", "js", "mdx"].some((e) => exists(`${pagesDir}/${s}.${e}`) || exists(`${pagesDir}/${s}/index.${e}`));
    } else {
      rel = `${publicDir}/${s}/index.html`;
      taken = exists(rel) || exists(`${publicDir}/${s}.html`);
    }
    if (taken) {
      skipped.push(`${it.title}: \`${it.path}\` already exists in this repo, left untouched`);
      continue;
    }
    write(rel, appDir ? nextAppPage(it.page) : pagesDir ? nextPagesPage(it.page) : it.page.html);
    written.push(`- **${it.title}** → \`${rel}\` (live at \`${it.path}\` after deploy)`);
    ids.push(it.fixId);
  } else if (it.kind === "llms-txt") {
    const rel = `${publicDir}/llms.txt`;
    if (exists(rel) || (appDir && exists(`${appDir}/llms.txt/route.ts`))) {
      skipped.push("llms.txt: you already have one, left untouched");
      continue;
    }
    write(rel, it.file);
    written.push(`- **${it.title}** → \`${rel}\``);
    ids.push(it.fixId);
  } else if (it.kind === "robots-txt") {
    const generated = appDir && ["ts", "js"].some((e) => exists(`${appDir}/robots.${e}`));
    const rel = `${publicDir}/robots.txt`;
    if (generated || exists(rel)) {
      manual.push(`**${it.title}**: you already have a robots.txt${generated ? ` (generated by ${appDir}/robots)` : ""}. Make sure it allows these AI search crawlers:\n\n\`\`\`\n${it.file.trim()}\n\`\`\``);
      continue;
    }
    write(rel, it.file);
    written.push(`- **${it.title}** → \`${rel}\``);
    ids.push(it.fixId);
  } else if (it.file) {
    manual.push(`**${it.title}**: ${it.note || ""}\n\n\`\`\`json\n${it.file.trim()}\n\`\`\``);
  }
}

const body = [
  "RankRoot prepared these changes from fixes you approved in your dashboard. They target questions where AI assistants currently recommend others instead of you.",
  "",
  written.length ? "### Added\n" + written.join("\n") : "",
  skipped.length ? "\n### Skipped\n" + skipped.map((s) => `- ${s}`).join("\n") : "",
  manual.length ? "\n### Needs a small manual change\n" + manual.join("\n\n") : "",
  "",
  `Detected setup: ${framework}. Review the pages, edit anything you like, and merge. RankRoot checks your live site each week and starts measuring each page's effect from the day it goes live.`,
].join("\n");
fs.writeFileSync(path.join(process.env.RUNNER_TEMP || "/tmp", "rankroot-pr-body.md"), body);
out("count", String(written.length));
out("ids", ids.join(","));
console.log(body);
